# ==================== 块2:考勤查询工具(等块1验收后再讲) ====================
@tool
def query_attendance(sql: str) -> str:
    """查询公司考勤数据库的工具
    数据库:attendance.db,表 attendance
    列:id(编号), name(员工姓名), date(日期), clock_in(上班打卡), clock_out(下班打卡)
    规则:clock_in 晚于 '09:00' 算迟到; clock_out 早于 '18:00' 算早退
    数据范围:5个员工(吴国谦、张三、李四、王五、赵六),2026-09-01 到 2026-09-12
    注意:本工具只查打卡记录(迟到/早退),不含扣款规则、报销标准等制度条款

    用法:传入一条SELECT查询语句,返回查询结果
    示例:"张三这个月迟到几次" -> SELECT COUNT(*) FROM attendance WHERE name='张三' AND clock_in > '09:00'
    """
    conn = sqlite3.connect("attendance.db")
    cur = conn.cursor()
    try:
        cur.execute(sql)
        results = cur.fetchall()
        return str(results)
    except Exception as e:
        return f"SQL 执行出错:{e}"
    finally:
        conn.close()

#==================== 包装search函数 ====================
@tool
def search_documents(question: str) -> str:
    """查询制度文档的工具
    覆盖文档:《差旅报销制度》、《考勤管理制度》
    用法:传入员工的完整问题,返回最相关的制度原文片段。
    适合:员工问公司规定(报销标准、考勤规则、请假制度等)时使用。
    当员工询问制度条款、规定标准(如迟到扣款、报销金额、请假天数)时,必须使用本工具
    """
    chunks = search(question)
    return "\n\n".join(chunks)

